# Revision analysis 03 -- the unified hierarchical meta-d' fit
# ===========================================================================
# ONE model specification, fitted to either sample:
#
#   first edition   318 subjects, 4 domains (memory, vision, GDP, Calories)
#   VMP replication 456 subjects, 2 domains (GDP, Calories)
#
#   Rscript revision/code/03_fit_unified.R --data revision/data/hmetad_trial.rds \
#           --out revision/models/fit_firstedition_fixed.rds
#   Rscript revision/code/03_fit_unified.R --data revision/data/hmetad_trial_vmp.rds \
#           --relative --out revision/models/fit_vmp_relative.rds
#   Rscript revision/code/03_fit_unified.R --nsub 8 --iter 200 --chains 1     # pilot
#   Rscript revision/code/03_fit_unified.R --contrast-sd 0.2 ...               # prior sensitivity
#
# --contrast-sd <num> sets the SD of the normal(0, sd) prior on EVERY mod<X>:fem_c gender
# contrast, on all 15 dpars, and changes nothing else. Default 0.5. When it is not the
# default the output filename gains a _csd<num> suffix, so a sensitivity fit can never
# overwrite the main fit.
#
# Replaces the old 03_fit_model.R (first edition, treatment-coded, buggy) and
# 03b_fit_vmp.R (VMP, sum-coded). Both are in git history.
#
# ---------------------------------------------------------------------------
# CODING. Fixed effects on EVERY distributional parameter:
#
#     ~ 0 + mod + mod:fem_c            fem_c = +0.5 Feminin, -0.5 Masculin
#
#   b_mod<X>          = the cell mean for domain X, averaged over genders
#   b_mod<X>:fem_c    = the gender effect (Feminin - Masculin) WITHIN domain X
#
# The domain-general effect is then the MEAN of the per-domain contrasts, computed
# draw-wise in 05_effects_unified.R -- not a coefficient. This is what the old
# treatment-coded model got wrong: under `gender * mod` with mod's reference level
# at memory, `genderFeminin` is the gender effect in the MEMORY task alone, and
# relabelling the domains would change it.
#
# Sum coding of gender (+/- 0.5) rather than a 0/1 dummy matters under cell means:
# with a dummy, b_mod<X> would silently become the reference gender's mean, and
# every population-level number in the output would be conditioned on being male.
#
# RANDOM EFFECTS are cell-means too, `(0 + mod | subj)`, one INDEPENDENT block per
# distributional parameter (brms gives each dpar its own block when no |tag| is
# shared -- and a tag that appears only once is inert decoration that reads as if
# parameters were correlated when they are not). Cell-means random effects make
# cor_subj__mod<X>__mod<Y> the between-domain correlation of log M: a model
# parameter with a posterior, rather than a correlation of shrunk point estimates.
#
# GENDER ENTERS ALL 15 DPARS, not just log M. M = meta-d'/d' is a ratio, so a gender
# difference in raw sensitivity divides out -- but only if d' is free to differ by
# gender. The dangerous parameters are the twelve type-2 criteria: men and women use
# the confidence scale differently in these data, and if the criteria cannot express
# that, the difference has nowhere to go but log M, manufacturing a spurious
# efficiency effect. Any gender effect on log M is therefore estimated CONDITIONAL
# ON gender effects in sensitivity, bias and scale usage.
#
# FIXED vs RELATIVE type-2 criteria. Default is hmetad's `metac_absolute = TRUE`
# (meta-c = c, "fixed"; matches the old MATLAB HMeta-d). `--relative` sets FALSE
# (meta-c/meta-d' = c/d'). Efficiency is largely insensitive to the choice; meta-Delta
# is not -- O'Neill, Zhan & Fleming (2026) show meta-Delta under the fixed model is
# biased in a non-linear, RESPONSE-SPECIFIC way when the data are generated by the
# relative model, unless c = 0 or meta-d' = d'. Fit both; report fixed as primary and
# relative as robustness. 05_effects_unified.R reports meta-Delta per response side
# precisely so the misspecification signature is visible.
# ---------------------------------------------------------------------------

.this <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
ROOT  <- normalizePath(if (length(.this)) file.path(dirname(.this[1]), "..", "..") else ".")
setwd(ROOT)
source("revision/code/helpers.R")

suppressMessages({ library(hmetad); library(brms); library(posterior); library(dplyr) })

DATA          <- getarg("--data", "revision/data/hmetad_trial.rds")
N_SUB         <- as.integer(getarg("--nsub", "0"))          # 0 = all subjects
ITER          <- as.integer(getarg("--iter", "2000"))
CHAINS        <- as.integer(getarg("--chains", "4"))
THREADS       <- as.integer(getarg("--threads", "1"))       # within-chain threads
SEED          <- as.integer(getarg("--seed", "1"))
ADAPT_DELTA   <- as.numeric(getarg("--adapt-delta", "0.95"))
MAX_TREEDEPTH <- as.integer(getarg("--max-treedepth", "12"))
REFRESH       <- as.integer(getarg("--refresh", "50"))
RELATIVE      <- hasflag("--relative")
METAC_ABS     <- !RELATIVE
CSD_ARG       <- getarg("--contrast-sd", "0.5")             # SD of the gender-contrast prior
CSD           <- as.numeric(CSD_ARG)
stopifnot(is.finite(CSD), CSD > 0)
CPRIOR        <- sprintf("normal(0, %s)", format(CSD))
OUT <- getarg("--out", sprintf("revision/models/fit_%s.rds",
                               if (RELATIVE) "relative" else "fixed"))
if (CSD != 0.5) OUT <- sub("\\.rds$", sprintf("_csd%s.rds", CSD_ARG), OUT)

dir.create(dirname(OUT), recursive = TRUE, showWarnings = FALSE)

# ------------------------------------------------------------------ data ----
d <- readRDS(DATA)
stopifnot(is.factor(d$mod), is.factor(d$gender), nlevels(d$gender) == 2,
          all(c("subj", "stimulus", "response", "confidence", "fem_c") %in% names(d)),
          all(sort(unique(d$fem_c)) == c(-0.5, 0.5)))
K <- max(d$confidence)
stopifnot(all(d$confidence %in% 1:K))

d <- subsample_subjects(d, N_SUB, seed = SEED)
d$fem_c <- ifelse(d$gender == "Feminin", 0.5, -0.5)   # re-derive after any subsetting

mods   <- levels(droplevels(d$mod))
d$mod  <- factor(d$mod, levels = mods)
cells  <- paste0("mod", mods)                  # domain cell means
contrs <- paste0("mod", mods, ":fem_c")        # per-domain gender contrasts
metac2 <- metac2_parameters(K = K)             # K = 7 -> 12 criterion log-spacings

cat(sprintf("data      : %s\n", DATA))
cat(sprintf("subjects  : %d (%s)\n", nlevels(d$subj),
            paste(sprintf("%s=%d", levels(d$gender),
                          tapply(d$subj, d$gender, function(x) length(unique(x)))),
                  collapse = " ")))
cat(sprintf("trials    : %d  cells: %d  domains: %s  K: %d\n",
            nrow(d), nrow(unique(d[, c("subj", "mod")])), paste(mods, collapse = ", "), K))

# Raw cell means BEFORE the model. If the model later says something these flatly
# contradict, that is a bug, not a finding.
cat("\n=== raw cell means (gender x domain) ===\n")
print(as.data.frame(d |> group_by(gender, mod) |>
        summarise(n = n(), accuracy = mean(stimulus == response),
                  mean_conf = mean(confidence), pct_top_bin = mean(confidence == K),
                  .groups = "drop")), row.names = FALSE, digits = 3)

# --------------------------------------------------------------- formula ----
rhs <- "~ 0 + mod + mod:fem_c + (0 + mod | subj)"
f <- bf(as.formula(paste("N",      rhs)),
        as.formula(paste("dprime", rhs)),
        as.formula(paste("c",      rhs))) +
     lf(as.formula(paste(paste(metac2, collapse = " + "), rhs)))

# ---------------------------------------------------------------- priors ----
# `0 + mod` means there is NO Intercept class: everything population-level is
# class "b". The cell-mean and the contrast coefficients therefore live in the same
# class, so the contrasts MUST be named with coef= or they would inherit the
# cell-mean prior -- which for d' is normal(1, 0.5), i.e. a prior asserting a gender
# difference of one unit of d'.
pr <- set_prior("normal(0, 0.5)",  class = "b", coef = cells)  +                   # log M
      set_prior(CPRIOR,            class = "b", coef = contrs) +
      set_prior("normal(1, 0.5)",  class = "b", coef = cells,  dpar = "dprime") +
      set_prior(CPRIOR,            class = "b", coef = contrs, dpar = "dprime") +
      set_prior("normal(0, 0.5)",  class = "b", coef = cells,  dpar = "c") +
      set_prior(CPRIOR,            class = "b", coef = contrs, dpar = "c") +
      set_prior("normal(0, 1)",    class = "sd") +                                 # log M
      set_prior("normal(0, 1)",    class = "sd", dpar = c("dprime", "c", metac2)) +
      set_prior("lkj(2)",          class = "cor")
for (p in metac2)                                                                  # criteria
  pr <- pr + set_prior("normal(-0.5, 1)", class = "b", coef = cells,  dpar = p) +
             set_prior(CPRIOR,            class = "b", coef = contrs, dpar = p)

# Resolve the priors against the actual design matrix and REFUSE to run if anything
# was left on a brms default or if a contrast inherited a non-zero-centred prior.
agg <- aggregate_metad(d, subj, mod, fem_c, K = K)
rp  <- validate_prior(pr, f, data = agg, family = metad(K = K, metac_absolute = METAC_ABS))

cat("\n=== resolved prior table ===\n")
print(as.data.frame(rp[, c("prior", "class", "coef", "group", "dpar", "source")]),
      row.names = FALSE)

# A blank `prior` on a coefficient row means "inherits the class-level prior above",
# which is fine. What is NOT fine is a row where brms has filled in a default of its
# own (non-empty prior, source != "user").
dflt <- rp[rp$prior != "" & rp$source != "user", ]
if (nrow(dflt)) { print(as.data.frame(dflt)); stop("a brms default prior is in force") }

bcoef <- rp[rp$class == "b" & rp$coef != "", ]
if (!all(bcoef$source == "user" & bcoef$prior != "")) {
  print(as.data.frame(bcoef[bcoef$source != "user", ])); stop("a population-level coefficient has no explicit prior")
}
bad <- bcoef[bcoef$coef %in% contrs & bcoef$prior != CPRIOR, ]
if (nrow(bad)) { print(as.data.frame(bad)); stop("a gender contrast has a non-zero-centred prior") }
cat(sprintf("prior check: OK -- %d population-level coefficients, all explicit; %d gender contrasts, all %s\n",
            nrow(bcoef), sum(bcoef$coef %in% contrs), CPRIOR))

# ------------------------------------------------------------------- fit ----
cat(sprintf("\nfitting: %d chains x %d iter (warmup %d), %d thread(s)/chain, seed %d\n",
            CHAINS, ITER, ITER %/% 2, THREADS, SEED))
cat(sprintf("confidence model requested: %s (metac_absolute = %s)\n",
            if (RELATIVE) "RELATIVE" else "FIXED", METAC_ABS))
cat(sprintf("gender-contrast prior: %s\n", CPRIOR))
t0 <- Sys.time()
m <- fit_metad(f, data = d, K = K, init = 0,
               metac_absolute = METAC_ABS,
               prior = pr, sample_prior = "yes",       # Savage-Dickey BFs post hoc
               chains = CHAINS, iter = ITER, warmup = ITER %/% 2,
               cores = CHAINS, seed = SEED, refresh = REFRESH,
               backend = "cmdstanr",
               threads = if (THREADS > 1) threading(THREADS) else NULL,
               control = list(adapt_delta = ADAPT_DELTA, max_treedepth = MAX_TREEDEPTH))
elapsed <- as.numeric(difftime(Sys.time(), t0, units = "secs"))

# Save BEFORE summarising. Hours of compute; summarise_draws on a fresh object can
# blow memory, and losing the fit to a post-processing error is unforgivable.
saveRDS(m, OUT)
cat("\nsaved ", OUT, "\n", sep = "")

# --------------------------------------------------------- diagnostics ----
fam <- fitted_confidence_model(m)
cat(sprintf("\nconfidence model FITTED (read from the fit object): %s  [%s]\n",
            toupper(fam$confidence_model), fam$name))
cat(sprintf("elapsed: %.0f s (%.2f h)\n", elapsed, elapsed / 3600))

np <- nuts_params(m)
cat(sprintf("divergent transitions: %d of %d post-warmup draws\n",
            sum(np$Parameter == "divergent__" & np$Value == 1),
            CHAINS * (ITER - ITER %/% 2)))

# Convergence on the REPORTED coefficients only. A max Rhat over ~15k random effects
# is dominated by nuisance terms and is close to meaningless.
sm  <- summarise_draws(as_draws_array(m, variable = "^b_.*fem_c$", regex = TRUE))
cat("\n=== reported coefficients (all gender contrasts) ===\n")
print(as.data.frame(sm[, c("variable", "mean", "q5", "q95", "rhat", "ess_bulk", "ess_tail")]),
      row.names = FALSE, digits = 3)
cat(sprintf("\nreported coefficients: max Rhat %.4f | min ESS_bulk %.0f | min ESS_tail %.0f\n",
            max(sm$rhat, na.rm = TRUE), min(sm$ess_bulk, na.rm = TRUE),
            min(sm$ess_tail, na.rm = TRUE)))

cat(sprintf("\nNext: Rscript revision/code/05_effects_unified.R --fit %s --tag <name>\n", OUT))
